import React, { useEffect, useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { Download, FileText, ExternalLink } from 'lucide-react';
import { PageHeader, SectionCard, LoadingOverlay, EmptyState, CategoryBadge, DemoBadge } from '../components/ui';
import { listReports } from '../services/api';
import type { GeneratedReport } from '../types';

const Reports: React.FC = () => {
  const [reports, setReports] = useState<GeneratedReport[]>([]);
  const [loading, setLoading] = useState(true);
  const navigate = useNavigate();

  useEffect(() => {
    listReports()
      .then(setReports)
      .finally(() => setLoading(false));
  }, []);

  return (
    <div className="max-w-5xl mx-auto space-y-5">
      <PageHeader
        title="Generated Reports"
        breadcrumb={['NAWI', 'Reports']}
        subtitle="PDF metrological test reports generated from saved session records"
      />

      <SectionCard
        title={`Reports (${reports.length})`}
        subtitle="All OIML R-76 metrological test reports"
        noPadding
      >
        {loading ? (
          <LoadingOverlay />
        ) : reports.length === 0 ? (
          <EmptyState
            title="No reports generated"
            description="Complete a test session and generate a PDF report to see it here."
            action={<button onClick={() => navigate('/tests')} className="btn-primary text-xs"><FileText size={14} /> Go to Tests</button>}
          />
        ) : (
          <table className="w-full">
            <thead>
              <tr>
                <th className="table-header">Report ID</th>
                <th className="table-header">Instrument</th>
                <th className="table-header">Test Session</th>
                <th className="table-header">Type</th>
                <th className="table-header">Generated By</th>
                <th className="table-header">Date</th>
                <th className="table-header">Actions</th>
              </tr>
            </thead>
            <tbody>
              {reports.map(r => (
                <tr key={r.id} className="hover:bg-slate-50 transition-colors">
                  <td className="table-cell font-mono text-xs">{r.id}</td>
                  <td className="table-cell">
                    <p className="font-medium text-sm text-slate-800">{r.instrument?.serial_number ?? r.instrument_id}</p>
                    <p className="text-xs text-slate-400">{r.instrument?.model}</p>
                  </td>
                  <td className="table-cell">
                    <button
                      onClick={() => navigate(`/tests/${r.test_session_id}`)}
                      className="font-mono text-xs text-blue-600 hover:underline"
                    >
                      {r.test_session_id}
                    </button>
                  </td>
                  <td className="table-cell text-xs text-slate-600">{r.report_type}</td>
                  <td className="table-cell text-xs text-slate-500">{r.generated_by}</td>
                  <td className="table-cell text-xs">{new Date(r.created_at).toLocaleDateString('en-IN')}</td>
                  <td className="table-cell">
                    <div className="flex gap-2">
                      <a
                        href={`/api/reports/${r.id}/download`}
                        target="_blank"
                        rel="noreferrer"
                        className="btn-primary py-1 text-xs"
                      >
                        <Download size={12} /> Download
                      </a>
                    </div>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        )}
      </SectionCard>
    </div>
  );
};

export default Reports;

